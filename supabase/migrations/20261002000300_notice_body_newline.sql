-- =====================================================================
-- 공지 본문의 글자 그대로 들어간 "\n" 을 진짜 줄바꿈으로 바꾼다
--
-- seed.sql 에서 '...\n...' 로 적은 문자열은 일반 SQL 문자열이라 \n 이 줄바꿈이 아니라
-- 역슬래시+n 두 글자로 저장됐고, 앱 화면에 \n 이 그대로 보였다.
-- seed.sql 은 E'...' (이스케이프 문자열) 로 고쳤고, 이미 들어간 데이터는 여기서 바로잡는다.
-- =====================================================================

-- LIKE 는 역슬래시를 이스케이프 문자로 쓰므로 패턴 매칭 대신 strpos 로 찾는다
update public.notices
   set body = replace(body, '\n', E'\n')
 where strpos(body, '\n') > 0;
